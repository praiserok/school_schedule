class Command(BaseCommand):
    help = 'Заповнити базу тестовими даними'

    def add_arguments(self, parser):
        parser.add_argument('--clear', action='store_true', help='Очистити перед заповненням')

    def handle(self, *args, **options):
        if options['clear']:
            TeacherSubject.objects.all().delete()
            SchoolClass.objects.all().delete()
            Room.objects.all().delete()
            Subject.objects.all().delete()
            Teacher.objects.all().delete()
            self.stdout.write('Базу очищено.')

        # Предмети
        subj_map = {}
        for name, short, double in SUBJECTS:
            s, _ = Subject.objects.get_or_create(
                name=name,
                defaults={'short_name': short, 'can_be_double': double},
            )
            subj_map[short] = s
        self.stdout.write(f'  Предмети: {Subject.objects.count()}')

        # Кабінети
        for room_name, subj_short, cap in ROOMS:
            Room.objects.get_or_create(
                name=room_name,
                defaults={
                    'subject': subj_map.get(subj_short) if subj_short else None,
                    'capacity': cap,
                },
            )
        self.stdout.write(f'  Кабінети: {Room.objects.count()}')

        # Вчителі
        teacher_map = {}
        for last, first, days, max_l in TEACHERS:
            t, _ = Teacher.objects.get_or_create(
                last_name=last, first_name=first,
                defaults={'available_days': days, 'max_lessons_per_day': max_l},
            )
            teacher_map[last] = t
        self.stdout.write(f'  Вчителі: {Teacher.objects.count()}')

        # Класи
        class_map = {}
        for grade, letter in CLASSES:
            c, _ = SchoolClass.objects.get_or_create(grade=grade, letter=letter)
            class_map[(grade, letter)] = c
        self.stdout.write(f'  Класи: {SchoolClass.objects.count()}')

        # Навантаження
        created = 0
        for last_name, subj_short, entries in ASSIGNMENTS:
            teacher = teacher_map.get(last_name)
            subject = subj_map.get(subj_short)
            if not teacher or not subject:
                self.stdout.write(self.style.WARNING(f'  ! Не знайдено: {last_name} / {subj_short}'))
                continue
            for grade, letter, hours in entries:
                cls = class_map.get((grade, letter))
                if not cls:
                    continue
                _, new = TeacherSubject.objects.get_or_create(
                    teacher=teacher, subject=subject, school_class=cls,
                    defaults={'hours_per_week': hours},
                )
                if new:
                    created += 1
        self.stdout.write(f'  Навантаження: {TeacherSubject.objects.count()} ({created} нових)')

        self.stdout.write(self.style.SUCCESS('Готово!'))
